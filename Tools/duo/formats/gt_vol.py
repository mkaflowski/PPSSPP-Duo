BLOCK = 0x800


class Vol:
    def __init__(self, path):
        self.f = open(path, 'rb')
        h = self.f.read(0x40)
        assert struct.unpack_from('<I', h)[0] == 0x71D319F3, 'not a GT PSP volume'
        h = h[:4] + h[4:0x24].translate(SBOX)
        toc_block, data_block, folders, toc_size = struct.unpack_from('<4i', h, 0x10)
        self.data_off = (1 + toc_block + data_block) * BLOCK
        self.f.seek((1 + toc_block) * BLOCK)
        self.toc = self.f.read(toc_size).translate(SBOX)
        self.pages = struct.unpack_from('<%dH' % (folders + 1), self.toc, 0)
        self.files = {}   # path -> (offset, stored, size, compressed)
        self._folder(self.pages[0] * 0x40, '')

    def _varint(self, p):
        # Bijective base 128: each continuation adds one before shifting.
        b = self.toc[p]; p += 1
        v = b & 0x7F
        while b & 0x80:
            v = (v + 1) << 7
            b = self.toc[p]; p += 1
            v += b & 0x7F
        return v, p

    def _folder(self, pos, parent):
        t = self.toc
        bits = t[pos] | t[pos + 1] << 8
        count = (bits >> 1) & 0x7FF
        p = pos + (12 * count + 7) // 8
        if bits & 1:   # index page
            subs = []
            for _ in range(count):
                hi = t[p]; p += 1
                n, p = self._varint(p)
                p += n
                subs.append(hi << 8 | t[p]); p += 1
            for s in subs:
                self._folder(self.pages[s] * 0x40, parent)
            return
        dirs = []
        for _ in range(count):
            flags = t[p]; p += 1
            n, p = self._varint(p)
            name = t[p:p + n].decode('ascii', 'replace'); p += n
            full = parent + '/' + name if parent else name
            if flags & 1:
                dirs.append((full, (flags >> 2) << 8 | t[p])); p += 1
            else:
                off, p = self._varint(p)
                if flags & 2:
                    stored, p = self._varint(p)
                    size, p = self._varint(p)
                else:
                    size, p = self._varint(p)
                    stored = size
                self.files[full] = (off * 0x40, stored, size, bool(flags & 2))
        for full, page in dirs:
            self._folder(self.pages[page] * 0x40, full)

    def read(self, path):
        off, stored, size, comp = self.files[path]
        o = self.data_off + off
        self.f.seek(o)
        data = bytearray(self.f.read(stored))
        for i in range(len(data)):
            data[i] ^= SBOX[(o + i) & 0xFF]
        if comp:
            assert struct.unpack_from('<I', data)[0] == 0xFFF7EEC5
            return zlib.decompress(bytes(data[8:]), -15)
        return bytes(data)


if __name__ == '__main__':
    v = Vol(sys.argv[1])
    if sys.argv[2] == 'list':
        for p, (off, stored, size, comp) in sorted(v.files.items()):
            print('%s\t%d\t%d\t%d' % (p, size, stored, comp))
    elif sys.argv[2] == 'extract':
        outdir = sys.argv[3]
        for pat in sys.argv[4:]:
            for p in sorted(v.files):
                if p == pat or (pat.endswith('*') and p.startswith(pat[:-1])):
                    out = os.path.join(outdir, *p.split('/'))
                    os.makedirs(os.path.dirname(out), exist_ok=True)
                    open(out, 'wb').write(v.read(p))
                    print(out)
